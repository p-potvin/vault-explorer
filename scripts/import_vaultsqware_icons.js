const targetIconsDir = path.resolve(__dirname, '..', 'icons');
const targetPublicIconsDir = path.resolve(__dirname, '..', 'public', 'icons');

function copyDirRecursive(src, dest) {
  if (!fs.existsSync(dest)) fs.mkdirSync(dest, { recursive: true });
  const entries = fs.readdirSync(src, { withFileTypes: true });
  for (const entry of entries) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

console.log('Copying icons to', targetIconsDir);
copyDirRecursive(sourceDir, targetIconsDir);

console.log('Copying icons to', targetPublicIconsDir);
copyDirRecursive(sourceDir, targetPublicIconsDir);

// Read icons manifest
const manifestPath = path.join(sourceDir, 'icons.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const svgDir = path.join(sourceDir, 'svg');

function toCamelCase(str) {
  return str.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());
}

// Map of inner SVG content by name
const iconSvgBodies = {};
for (const icon of manifest.icons) {
  const svgFile = path.join(svgDir, `${icon.name}.svg`);
  if (fs.existsSync(svgFile)) {
    let content = fs.readFileSync(svgFile, 'utf8').trim();
    // Extract inner content of <svg ...> ... </svg>
    const match = content.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i);
    if (match) {
      iconSvgBodies[icon.name] = match[1].trim();
    }
  }
}

console.log(`Extracted SVG body for ${Object.keys(iconSvgBodies).length} icons.`);

